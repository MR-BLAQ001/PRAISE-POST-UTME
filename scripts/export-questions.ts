import { mkdirSync, writeFileSync } from "node:fs";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";
import { SEED_QUESTIONS } from "../src/lib/questions";

const here = dirname(fileURLToPath(import.meta.url));
const outputJson = resolve(here, "../supabase/questions.seed.json");
const outputSql = resolve(here, "../supabase/questions.seed.sql");

mkdirSync(dirname(outputJson), { recursive: true });

const payload = SEED_QUESTIONS.map((question) => ({
  id: question.id,
  subject: question.subject,
  topic: question.topic,
  difficulty: question.difficulty,
  text: question.text,
  options: question.options,
  correct_index: question.correctIndex,
  explanation: question.explanation,
  source: question.source,
  is_custom: Boolean(question.isCustom),
  created_at: question.createdAt ?? "2026-01-01T00:00:00.000Z"
}));

writeFileSync(outputJson, `${JSON.stringify(payload, null, 2)}\n`, "utf8");

function sqlString(value: string) {
  return `'${value.replace(/'/g, "''")}'`;
}

const rows = payload
  .map(
    (question) =>
      `  (${sqlString(question.id)}, ${sqlString(question.subject)}, ${sqlString(
        question.topic
      )}, ${sqlString(question.difficulty)}, ${sqlString(question.text)}, ${sqlString(
        JSON.stringify(question.options)
      )}::jsonb, ${question.correct_index}, ${sqlString(question.explanation)}, ${sqlString(
        question.source
      )}, false, ${sqlString(question.created_at)})`
  )
  .join(",\n");

const sql = `-- Generated by npm run export:questions. Do not edit by hand.
-- Run this after supabase/schema.sql to load the 800-question seed bank.
insert into public.questions
  (id, subject, topic, difficulty, text, options, correct_index, explanation, source, is_custom, created_at)
values
${rows}
on conflict (id) do update set
  subject = excluded.subject,
  topic = excluded.topic,
  difficulty = excluded.difficulty,
  text = excluded.text,
  options = excluded.options,
  correct_index = excluded.correct_index,
  explanation = excluded.explanation,
  source = excluded.source,
  is_custom = excluded.is_custom;
`;

writeFileSync(outputSql, sql, "utf8");

console.log(`Wrote ${payload.length} questions to:`);
console.log(`  ${outputJson}`);
console.log(`  ${outputSql}`);
